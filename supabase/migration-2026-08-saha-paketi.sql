-- Sıklık → interval. Bilinmeyen değer haftalık sayılır.
create or replace function public.recurrence_interval(p_freq text)
returns interval language sql immutable as $$
  select case lower(coalesce(p_freq,''))
           when 'gunluk' then interval '1 day'
           when 'aylik'  then interval '1 month'
           else               interval '7 days'
         end;
$$;

-- Düzenli ilan oluşturulunca / işaretlenince sıradaki seferin saatini kur.
-- İstemcide hesaplamak yerine trigger: admin "adına ilan" akışı ve ileride
-- eklenecek her yol otomatik doğru olur. recurring kaldırılırsa sıra silinir
-- (= üyenin "tekrarı durdur" düğmesi tam olarak bu).
create or replace function public.set_next_run()
returns trigger language plpgsql set search_path = public as $$
begin
  if new.recurring is true then
    -- Kopya ilanlar (parent_id dolu) ŞABLON DEĞİLDİR; onlara sıra kurulmaz.
    if new.parent_id is null and new.next_run_at is null then
      new.next_run_at := now() + public.recurrence_interval(new.recurring_freq);
    end if;
  else
    new.next_run_at := null;
  end if;
  return new;
end; $$;
drop trigger if exists listings_set_next_run on public.listings;
create trigger listings_set_next_run
  before insert or update of recurring, recurring_freq on public.listings
  for each row execute function public.set_next_run();

-- ── Çekirdek: bir şablonun sırası geldiyse yeni seferi aç ──────────
-- p_owner null ise TÜM sahiplerin şablonları taranır (yalnız admin çağırır).
-- Döner: açılan yeni ilan sayısı.
--
-- KURALLAR (hepsi bilinçli):
--  • Şablon = recurring + next_run_at dolu ilan. Kopya İLAN ŞABLON DEĞİLDİR
--    (recurring=false, parent_id dolu) — yoksa üstel çoğalma olurdu.
--  • DURDURMA = recurring'i false yapmak (İlanlarım'daki düğme). Şablonun
--    'kapali'/'eslesti' olması tekrarı DURDURMAZ: "her salı 3 tır" işinin
--    şablonu zaten her hafta eşleşip kapanır — durum'a bakmak özelliği
--    ilk sefer sonrası sessizce öldürürdü.
--  • Şablonun kendisi ya da ondan doğmuş bir kopya HÂLÂ AÇIK (aktif) ise
--    yeni sefer AÇILMAZ; sıra yine ilerletilir. Geçen haftaki iş kamyon
--    bulamadıysa panoya bir tane daha atmak panoyu çöplendirir.
--  • Öncelik: önceki seferi kabul eden nakliyeci varsa yeni ilan 12 saat
--    ona ayrılır (accept_job bunu uygular). Süre dolunca herkese açılır.
--  • Sıra ilerletme ile kopyalama AYNI transaction'da; skip locked ile iki
--    eşzamanlı çağrı aynı seferi iki kez açamaz.
create or replace function public.run_recurrences(p_owner uuid)
returns int language plpgsql security definer set search_path = public as $$
declare
  t         public.listings;
  v_iv      interval;
  v_acik    boolean;
  v_prev    uuid;
  v_next    timestamptz;
  v_count   int := 0;
begin
  for t in
    select * from public.listings
     where recurring is true
       and parent_id is null
       and next_run_at is not null
       and next_run_at <= now()
       and (p_owner is null or owner_id = p_owner)
     for update skip locked
  loop
    v_iv := public.recurrence_interval(t.recurring_freq);

    -- Sırayı HER durumda ilerlet (atlanan sefer birikmesin). Geçmişte
    -- kalmış birden çok periyot varsa tek adımda bugünden SONRAKİ ilk
    -- sefere atla (min: sonraki, max olsaydı seriyi sonuna taşırdı).
    select min(x) into v_next
      from generate_series(t.next_run_at, now() + v_iv, v_iv) g(x)
     where x > now();
    update public.listings
       set next_run_at = coalesce(v_next, now() + v_iv)
     where id = t.id;

    -- Şablonun kendisi ya da bir kopyası hâlâ açık mı?
    v_acik := (t.status = 'aktif') or exists (
      select 1 from public.listings c
       where c.parent_id = t.id and c.status = 'aktif'
    );
    if v_acik then
      continue;   -- önceki sefer daha kapanmadı: yenisini açma
    end if;

    -- Önceki seferi kim aldıysa ona öncelik (en yeni kopya, yoksa şablonun kendisi).
    select c.accepted_by_id into v_prev
      from public.listings c
     where c.parent_id = t.id and c.accepted_by_id is not null
     order by c.created_at desc limit 1;
    if v_prev is null then v_prev := t.accepted_by_id; end if;

    insert into public.listings (
      type, cat, title, il, ilce, varis_il, yukleme, bosaltma, material, amount, unit,
      date_text, recurring, recurring_text, recurring_freq, recurring_duration, daily_trips,
      vehicle, capacity, price_type, price, description, km, pickup, dropoff,
      owner_id, owner_name, owner_logo, owner_verified, owner_rating,
      status, created_text, parent_id, reserved_for_id, reserved_until
    )
    select
      t.type, t.cat, t.title, t.il, t.ilce, t.varis_il, t.yukleme, t.bosaltma, t.material, t.amount, t.unit,
      t.date_text, false, t.recurring_text, t.recurring_freq, t.recurring_duration, t.daily_trips,
      t.vehicle, t.capacity, t.price_type, t.price, t.description, t.km, t.pickup, t.dropoff,
      t.owner_id, t.owner_name, t.owner_logo, t.owner_verified, t.owner_rating,
      'aktif', 'az once', t.id, v_prev,
      case when v_prev is null then null else now() + interval '12 hours' end;

    v_count := v_count + 1;
  end loop;
  return v_count;
end; $$;
revoke all on function public.run_recurrences(uuid) from public, anon, authenticated;

-- Üye kendi düzenli işlerini işletir (uygulama açılışında bir kez çağrılır).
create or replace function public.run_my_recurrences()
returns int language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then return 0; end if;
  return public.run_recurrences(auth.uid());
end; $$;
revoke all on function public.run_my_recurrences() from public, anon;
grant execute on function public.run_my_recurrences() to authenticated;

