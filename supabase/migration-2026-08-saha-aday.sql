-- 3) SÜRÜCÜ GUARD'I — SAHİPLENME İSTİSNASI
-- ════════════════════════════════════════════════════════════════════
-- schema.sql'deki sürümün BİREBİR üstüne yazılır; mevcut iki istisna (doğrudan
-- kabul + iptal) ve iç-trigger muafiyeti KORUNUR, sonuna üçüncüsü eklenir.
--
-- NEDEN ŞART: claim_prospect owner_id/owner_name/owner_* kolonlarını yazar ama
-- çağıran taraf ne ilan sahibi (owner_id null) ne admin. SECURITY DEFINER RLS'i
-- atlar, TRIGGER'I ATLAMAZ — bu istisna olmadan sahiplenme her seferinde
-- "Sürücü yalnız sefer alanlarını güncelleyebilir" ile patlardı. (Aynı tuzak
-- daha önce iş kabulünü kırmıştı: migration-2026-07-kabul-guard-fix.sql.)
create or replace function public.guard_driver_listing_update()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  allowed text[] := array['phase','status','cycle_stage','arrived_at','trips_done','delivery_proof','payment_received_at','payment_paid_at'];
begin
  -- İç-trigger muafiyeti: sync_offers_count gibi sistem trigger'larının yaptığı
  -- listings güncellemeleri (pg_trigger_depth 2+) kullanıcı kısıtına takılmasın.
  if pg_trigger_depth() > 1 then return new; end if;
  -- Sahip, admin ve doğrudan SQL (auth.uid() null) tam yetkili; yalnız sürücü kısıtlanır.
  if auth.uid() is null or auth.uid() = old.owner_id or public.is_admin() then
    return new;
  end if;
  -- DOĞRUDAN KABUL geçişi (aktif → eslesti): tek seferlik kendini-atama.
  if old.status = 'aktif' and new.status = 'eslesti'
     and old.accepted_by_id is null and new.accepted_by_id = auth.uid() then
    allowed := allowed || array['accepted_by_id','assigned_vehicle'];
  end if;
  -- İPTAL geçişi (eslesti → aktif, kabulün simetriği).
  if old.status = 'eslesti' and new.status = 'aktif'
     and old.accepted_by_id = auth.uid() and new.accepted_by_id is null then
    allowed := allowed || array['accepted_by_id','assigned_vehicle'];
  end if;
  -- YENİ — SAHİPLENME geçişi (saha aday kaydı): sahipsiz vitrin ilanı, firma
  -- kendi hesabını açınca ona devredilir. Güvenli, çünkü üç koşul birden aranır:
  --   • ilan gerçekten SAHİPSİZ (old.owner_id is null)
  --   • bir ADAY KAYDA bağlı (old.prospect_id is not null) — rastgele demo ilan değil
  --   • ve yalnız KENDİNE atanabilir (new.owner_id = auth.uid())
  -- Jetonu bilmeyen zaten claim_prospect'ten geçemez; bu istisna son kapıdır.
  if old.owner_id is null and old.prospect_id is not null
     and new.owner_id = auth.uid()
     and new.prospect_id is not distinct from old.prospect_id then
    allowed := allowed || array['owner_id','owner_name','owner_logo','owner_verified','owner_rating'];
  end if;
  if (to_jsonb(new) - allowed) is distinct from (to_jsonb(old) - allowed) then
    raise exception 'Sürücü yalnız sefer alanlarını güncelleyebilir';
  end if;
  return new;
end; $$;
drop trigger if exists on_listing_driver_guard on public.listings;
create trigger on_listing_driver_guard
  before update on public.listings
  for each row execute function public.guard_driver_listing_update();


-- ════════════════════════════════════════════════════════════════════
-- 4) YAYINLA / GERİ AL — admin
-- ════════════════════════════════════════════════════════════════════
-- Taslak adayın ilanları 'kapali' durur (panoda görünmez). Yayınlamak, aday
-- kaydı ile bağlı TÜM vitrin ilanlarını tek dokunuşta canlıya alır.
create or replace function public.publish_prospect(p_id bigint)
returns public.prospects language plpgsql security definer set search_path = public as $$
declare p public.prospects;
begin
  if not public.is_admin() then raise exception 'Yetki yok.'; end if;
  select * into p from public.prospects where id = p_id for update;
  if not found then raise exception 'Aday kayıt bulunamadı.'; end if;
  -- Kısıt zaten engelliyor; buradaki amaç panelde ANLAŞILIR hata göstermek.
  if p.consent_at is null then
    raise exception 'Rıza kaydı yok — firma "evet" demeden vitrin yayınlanamaz.';
  end if;
  update public.prospects set status = 'yayinda' where id = p_id returning * into p;
  update public.listings set status = 'aktif'
   where prospect_id = p_id and owner_id is null and status = 'kapali';
  return p;
end; $$;
revoke all on function public.publish_prospect(bigint) from public, anon;
grant execute on function public.publish_prospect(bigint) to authenticated;

create or replace function public.unpublish_prospect(p_id bigint)
returns public.prospects language plpgsql security definer set search_path = public as $$
declare p public.prospects;
begin
  if not public.is_admin() then raise exception 'Yetki yok.'; end if;
  select * into p from public.prospects where id = p_id for update;
  if not found then raise exception 'Aday kayıt bulunamadı.'; end if;
  -- Sahiplenilmiş adayın ilanları artık ÜYENİN malı; saha ekibi geri alamaz.
  if p.claimed_by is not null then
    raise exception 'Bu firma hesabını açtı — ilanları artık ona ait, buradan geri alınamaz.';
  end if;
  update public.prospects set status = 'kapali' where id = p_id returning * into p;
  update public.listings set status = 'kapali'
   where prospect_id = p_id and owner_id is null;
  return p;
end; $$;
revoke all on function public.unpublish_prospect(bigint) from public, anon;
grant execute on function public.unpublish_prospect(bigint) to authenticated;


