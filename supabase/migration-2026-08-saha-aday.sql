-- 1) ADAY KAYIT — public.prospects
-- ════════════════════════════════════════════════════════════════════
-- auth.users'a BAĞLI DEĞİL — kilidi açan şey tam olarak bu. Kişisel veri
-- (phone/email/note) YALNIZ admin tarafından okunur; hiçbir görünüme,
-- hiçbir anon RPC'ye sızmaz.
create table if not exists public.prospects (
  id           bigint generated by default as identity primary key,
  -- Davet linki jetonu. Mevcut üreteç iki kez: 12 karakter, karışan harf yok
  -- (0/O, 1/I/L). Telefonda okunacak kadar kısa, tahmin edilemeyecek kadar geniş.
  token        text not null unique default (public.gen_invite_code() || public.gen_invite_code()),
  name         text not null,
  role         text not null default '',   -- isveren | tedarikci | nakliyeci
  -- SAHA NOTU — yayınlanmaz. Vitrin ilanında firmanın numarası DEĞİL saha hattı görünür.
  phone        text not null default '',
  email        text not null default '',
  il           text not null default '',
  ilce         text not null default '',
  -- profiles'taki satıcı alanlarıyla birebir: sahiplenmede doğrudan kopyalanır.
  tesis_turu   text not null default '',
  hakkinda     text not null default '',
  malzemeler   text[] not null default '{}',
  note         text not null default '',   -- ziyaret / CRM notu
  status       text not null default 'taslak',
  -- RIZA: firma "evet" dedi mi, ne zaman, nasıl belgelendi.
  consent_at   timestamptz,
  consent_note text not null default '',
  claimed_by   uuid references public.profiles(id) on delete set null,
  claimed_at   timestamptz,
  created_by   uuid references public.profiles(id) on delete set null,
  created_at   timestamptz not null default now(),
  constraint prospects_status_chk check (status in ('taslak','yayinda','sahiplenildi','kapali')),
  constraint prospects_role_chk   check (role in ('','isveren','tedarikci','nakliyeci')),
  -- ── RIZA KAPISI ──────────────────────────────────────────────────
  -- OCAK-LISTESI.md'nin kuralı ("yayınlanmış uygulamada firma adına izinsiz
  -- ilan olmaz") artık bir belge tavsiyesi değil, VERİTABANI KISITI. Panelde
  -- düğmeyi gizlemek yetmez: rıza damgası yokken 'yayinda' satırı yazılamaz.
  constraint prospects_consent_chk check (status <> 'yayinda' or consent_at is not null)
);
create index if not exists prospects_status_idx  on public.prospects (status, created_at desc);
create index if not exists prospects_claimed_idx on public.prospects (claimed_by) where claimed_by is not null;

alter table public.prospects enable row level security;
drop policy if exists prospects_admin_all on public.prospects;
-- Okuma da yazma da YALNIZ admin. Kayıtsız/üye tarafın tek erişimi
-- prospect_by_token RPC'sidir ve o yalnız firma adı + il döndürür.
create policy prospects_admin_all on public.prospects
  for all using (public.is_admin()) with check (public.is_admin());
grant select, insert, update, delete on public.prospects to authenticated;


