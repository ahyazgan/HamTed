-- Karışması kolay harf/rakam YOK (0/O, 1/I/L). Kod telefonda okunacak.
create or replace function public.gen_invite_code()
returns text language sql volatile as $$
  select string_agg(substr('ABCDEFGHJKMNPQRSTUVWXYZ23456789',
                           (floor(random()*31)::int)+1, 1), '')
    from generate_series(1,6);
$$;

-- Kendi davet kodum (yoksa üretir). Kısa ve tekrar çağrılabilir.
create or replace function public.my_invite_code()
returns text language plpgsql security definer set search_path = public as $$
declare me uuid := auth.uid(); v_code text; i int := 0;
begin
  if me is null then raise exception 'Giriş gerekli.'; end if;
  select invite_code into v_code from public.profiles where id = me;
  if v_code is not null and v_code <> '' then return v_code; end if;
  loop
    i := i + 1;
    v_code := public.gen_invite_code();
    begin
      update public.profiles set invite_code = v_code where id = me;
      return v_code;
    exception when unique_violation then
      if i > 8 then raise exception 'Davet kodu üretilemedi, tekrar dene.'; end if;
    end;
  end loop;
end; $$;
revoke all on function public.my_invite_code() from public, anon;
grant execute on function public.my_invite_code() to authenticated;

-- Davet kodunu sahiplen. YALNIZ bir kez (invited_by boşken) yazılır;
-- kendi kodunu kullanmak ve 30 günden eski hesaba geriye dönük atıf yok.
-- Döner: true = atıf yazıldı.
create or replace function public.claim_invite(p_code text)
returns boolean language plpgsql security definer set search_path = public as $$
declare me uuid := auth.uid(); v_owner uuid; v_mine uuid; v_created timestamptz;
begin
  if me is null or coalesce(p_code,'') = '' then return false; end if;
  select invited_by, created_at into v_mine, v_created from public.profiles where id = me;
  if v_mine is not null then return false; end if;
  if v_created is not null and v_created < now() - interval '30 days' then return false; end if;
  select id into v_owner from public.profiles
   where invite_code is not null and upper(invite_code) = upper(trim(p_code));
  if v_owner is null or v_owner = me then return false; end if;
  update public.profiles set invited_by = v_owner where id = me and invited_by is null;
  return found;
end; $$;
revoke all on function public.claim_invite(text) from public, anon;
grant execute on function public.claim_invite(text) to authenticated;

-- Kaç kişiyi getirdim? (Üye başkasının satırını okuyamaz; sayıyı RPC verir.)
create or replace function public.my_invite_count()
returns int language sql security definer set search_path = public as $$
  select count(*)::int from public.profiles where invited_by = auth.uid();
$$;
revoke all on function public.my_invite_count() from public, anon;
grant execute on function public.my_invite_count() to authenticated;


