select relname, relrowsecurity from pg_class where relname = 'prospects';
-- 1a) rıza kapısı dahil 3 kısıt:
select conname from pg_constraint where conrelid = 'public.prospects'::regclass
   and contype = 'c' order by conname;
-- 1b) tek politika (prospects_admin_all):
select policyname from pg_policies where tablename = 'prospects';
-- 2) vitrin bağı (1 satır):
select column_name from information_schema.columns
 where table_schema='public' and table_name='listings' and column_name='prospect_id';
-- 3) sürücü guard'ı ÜÇ istisnayı da taşıyor mu? (üçü de true)
select prosrc like '%accepted_by_id = auth.uid()%'   as kabul_var,
       prosrc like '%new.accepted_by_id is null%'    as iptal_var,
       prosrc like '%old.prospect_id is not null%'   as sahiplenme_var
  from pg_proc join pg_namespace n on n.oid = pronamespace
 where n.nspname='public' and proname='guard_driver_listing_update';
-- 4-5) RPC'ler (4 satır):
select proname from pg_proc join pg_namespace n on n.oid = pronamespace
 where n.nspname='public'
   and proname in ('publish_prospect','unpublish_prospect','prospect_by_token','claim_prospect')
 order by proname;
